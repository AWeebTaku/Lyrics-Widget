#!/usr/bin/env node
// Writes the settings page files (plasmoid/contents/ui/config*.qml) from settings/model.js and config/main.xml.
// Plasma finds a setting on a page by its `cfg_<key>` property, so each page declares exactly the keys of its model page
// (and the `Default` twin Plasma fills with the default); everything else is drawn by settings/SettingsPage.qml.
// Run: node tools/gen-settings.js        (tests/settings.test.js fails when the pages are out of date)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..", "plasmoid", "contents");
const ui = path.join(root, "ui");

const M = new Function(fs.readFileSync(path.join(ui, "settings", "model.js"), "utf8").replace(".pragma library", "") + ";return {pages, pageKeys}")();
const xml = fs.readFileSync(path.join(root, "config", "main.xml"), "utf8");
const types = {};
for (const m of xml.matchAll(/<entry name="(\w+)" type="(\w+)"/g)) types[m[1]] = m[2];
const qml = { Bool: "bool", Int: "int", Double: "real", String: "string", StringList: "var" };

// model page -> file
const files = { general: "configGeneral.qml", lyrics: "configLyrics.qml", visualizer: "configVisualizer.qml", audio: "configAudio.qml",
                card: "configCard.qml", sources: "configAccounts.qml" };

function page(p) {
    const decl = M.pageKeys(p).map(k => {
        if (!types[k]) throw new Error(`${p.id}: ${k} is not in main.xml`);
        const t = qml[types[k]];
        return `    property ${t} cfg_${k}\n    property ${t} cfg_${k}Default`;
    }).join("\n");
    return `// GENERATED by tools/gen-settings.js from settings/model.js: do not edit by hand (edit the model, then run the generator).
import QtQuick
import org.kde.kirigami as Kirigami
import org.kde.kcmutils as KCM
import "wide.js" as Wide
import "settings"

// ${p.title}: ${p.subtitle}
KCM.SimpleKCM {
    id: page
    // a wide settings window; the page may not be in its window yet when it is created
    Component.onCompleted: Wide.grow(Window.window, Kirigami.Units.gridUnit)
    Window.onWindowChanged: Wide.grow(Window.window, Kirigami.Units.gridUnit)

${decl}

    SettingsPage { kcm: page; pageId: "${p.id}" }
}
`;
}

let n = 0;
for (const p of M.pages) {
    if (!files[p.id]) throw new Error("no file for page " + p.id);
    fs.writeFileSync(path.join(ui, files[p.id]), page(p));
    ++n;
}
console.log(`wrote ${n} pages`);
