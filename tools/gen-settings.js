#!/usr/bin/env node
// Writes the settings page files (plasmoid/contents/ui/config*.qml) from settings/model.js and config/main.xml.
// Plasma finds a setting on a page by its `cfg_<key>` property, so each page declares exactly the keys of its model page
// (and the `Default` twin Plasma fills with the default); everything else is drawn by settings/SettingsPage.qml.
// Run: node tools/gen-settings.js        (tests/settings.test.js fails when the pages are out of date)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..", "plasmoid", "contents");
const ui = path.join(root, "ui");

const M = new Function(fs.readFileSync(path.join(ui, "settings", "model.js"), "utf8").replace(".pragma library", "") + ";return {pages, pageKeys}")();
const xml = fs.readFileSync(path.join(root, "config", "main.xml"), "utf8");
const types = {};
for (const m of xml.matchAll(/<entry name="(\w+)" type="(\w+)"/g)) types[m[1]] = m[2];
const qml = { Bool: "bool", Int: "int", Double: "real", String: "string", StringList: "var" };

// model page -> file
const files = { general: "configGeneral.qml", lyrics: "configLyrics.qml", visualizer: "configVisualizer.qml", audio: "configAudio.qml",
                card: "configCard.qml", looks: "configLooks.qml", sources: "configAccounts.qml" };

function page(p) {
    const decl = M.pageKeys(p).map(k => {
        if (!types[k]) throw new Error(`${p.id}: ${k} is not in main.xml`);
        const t = qml[types[k]];
        return `    property ${t} cfg_${k}\n    property ${t} cfg_${k}Default`;
    }).join("\n");
    return `// GENERATED by tools/gen-settings.js from settings/model.js: do not edit by hand (edit the model, then run the generator).
import QtQuick
import org.kde.kirigami as Kirigami
import org.kde.kcmutils as KCM
import "wide.js" as Wide
import "settings"

// ${p.title}: ${p.subtitle}
KCM.SimpleKCM {
    id: page
    // a wide settings window; the page may not be in its window yet when it is created
    Component.onCompleted: Wide.grow(Window.window, Kirigami.Units.gridUnit)
    Window.onWindowChanged: Wide.grow(Window.window, Kirigami.Units.gridUnit)

${decl}

    SettingsPage { kcm: page; pageId: "${p.id}" }
}
`;
}

// the defaults, for the stand-alone settings window (Plasma fills the `...Default` values itself in its own dialog)
const defaults = {};
for (const m of xml.matchAll(/<entry name="(\w+)" type="(\w+)">([\s\S]*?)<\/entry>/g)) {
    const d = (/<default[^>]*>([\s\S]*?)<\/default>/.exec(m[3]) || [0, ""])[1].trim();
    defaults[m[1]] = m[2] === "Bool" ? d === "true" : m[2] === "Int" || m[2] === "Double" ? Number(d || 0) : m[2] === "StringList" ? d.split(",").filter(x => x) : d;
}

// the same page for the widget's own settings window (SettingsWindow.qml), which can be open for several widgets at once
// (Plasma's own dialog is one at a time): a scrolling panel with the same cfg_ properties, load() and save()
function panel(p) {
    const keys = M.pageKeys(p);
    const decl = keys.map(k => {
        const t = qml[types[k]];
        return `    property ${t} cfg_${k}\n    property ${t} cfg_${k}Default`;
    }).join("\n");
    const def = {};
    for (const k of keys) def[k] = defaults[k];
    return `// GENERATED by tools/gen-settings.js from settings/model.js: do not edit by hand (edit the model, then run the generator).
import QtQuick
import QtQuick.Controls as QQC2

// ${p.title}, for the widget's own settings window. The same page as in Plasma's settings dialog; load() fills it from the
// widget's configuration, save() writes back what changed (and says how many settings that was).
QQC2.ScrollView {
    id: panel
    // a fixed implicit size: the window's layout gives the real one (a size that follows availableWidth is a binding loop)
    implicitWidth: 100
    implicitHeight: 100
    contentWidth: availableWidth
    clip: true
    readonly property var keys: ${JSON.stringify(keys)}
    readonly property var defaults: (${JSON.stringify(def)})

${decl}

    function load(cfg) {
        if (!cfg) return
        for (const k of keys) {
            panel["cfg_" + k] = cfg[k]
            panel["cfg_" + k + "Default"] = defaults[k]
        }
    }
    function save(cfg) {
        let changed = 0
        if (!cfg) return 0
        for (const k of keys) {
            const v = panel["cfg_" + k]
            if (JSON.stringify(v) !== JSON.stringify(cfg[k])) { cfg[k] = v; ++changed }
        }
        return changed
    }

    SettingsPage { kcm: panel; pageId: "${p.id}"; width: panel.availableWidth }
}
`;
}

let n = 0;
for (const p of M.pages) {
    if (!files[p.id]) throw new Error("no file for page " + p.id);
    fs.writeFileSync(path.join(ui, files[p.id]), page(p));
    fs.writeFileSync(path.join(ui, "settings", p.id[0].toUpperCase() + p.id.slice(1) + "Panel.qml"), panel(p));
    ++n;
}
console.log(`wrote ${n} pages and ${n} panels`);
